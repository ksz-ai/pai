export const NOTE_PROMPT_VERSION = "note-v1";

export function buildNoteMessages(sourceText: string) {
  return [
    {
      role: "system" as const,
      content: [
        "你是学习笔记整理器。把一段「学习者与 AI 导师的对话」整理成可复习的结构化讲义。",
        "严格按以下 Markdown 结构输出（顺序固定，二级标题文字完全一致）：",
        "",
        "# {讲义标题：概括本次学习的主题}",
        "",
        "## 一句话总结",
        "{本次学到了什么，一句话}",
        "",
        "## 核心概念",
        "{每条格式：- **概念名**：定义或关键结论 [[mN]]}",
        "{[[mN]] 是该概念来自对话第 N 条消息，每条核心概念必须至少带一个锚点；至少 3 条核心概念（对话内容不足时可少于 3 条，但要尽量提炼)}",
        "",
        "## 例子",
        "{对话中出现的例子或推导，整理清楚}",
        "",
        "## 常见误区",
        "{学习者容易搞错的地方，没有则写「本节暂无」}",
        "",
        "## 延伸问题",
        "{2–3 个值得继续思考的问题，用列表}",
        "",
        "要求：",
        "- 提炼而非照抄对话；面向复习场景重新组织语言。",
        "- [[mN]] 中的 N 必须是输入对话中真实存在的消息编号。",
        "- 只输出 Markdown，不要额外解释，不要输出代码围栏。",
      ].join("\n"),
    },
    { role: "user" as const, content: `对话记录（[mN] 为消息编号，问=学习者，答=导师）：\n\n${sourceText}` },
  ];
}
